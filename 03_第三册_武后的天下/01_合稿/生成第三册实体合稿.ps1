## 全册史料说明

本册以《旧唐书》《新唐书》《资治通鉴》为主要叙事骨架，并参照《唐律疏议》《唐会要》《通典》及相关墓志、制度材料。各章末尾另列主要参考与具体使用边界。

高宗、武后时期的材料有一个明显难题：许多宫廷细节由后来的胜利者、反对者或道德评价者保存。本文不因材料写得生动便自动相信，也不因记载带有立场便全部放弃。能够由不同材料互相支持的事件作为骨架；单一来源中的精确对白、寝殿行动、祥瑞和内心计划，以“史书记载”“可能”“未必”等措辞保留距离。

对长孙无忌案、李贤案、酷吏案件和神龙政变，正文区分政治动机、法律罪名、办案程序与最后结果。朝廷判决是历史事实，不自动等于指控内容已经得到现代意义上的证明；后人认为存在构陷，也需要落实到口供取得、物证缺失、对质机会和受益结构，而不能只靠同情失败者。

对外关系部分不把唐朝地图上的设置直接等同于长期有效控制。百济、高句丽、西突厥、吐蕃、后突厥、契丹与新罗都有自己的目标；唐军能够抵达，不表示州县、军粮、交通与地方合作会自动稳定。都护府、羁縻州、册封、和亲与互市既是统治工具，也是谈判结果。

本册写到神龙元年。武则天退位与去世结束了武周，却没有让她改变的选官渠道、官僚结构和政治记忆一同消失。制度比个人活得更久，也因此更值得继续追问。
'@

$parts = [System.Collections.Generic.List[string]]::new()
$parts.Add($frontMatter.TrimEnd())

foreach ($fileName in $chapterFiles) {
    $chapterPath = Join-Path $chapterRoot $fileName
    if (-not (Test-Path -LiteralPath $chapterPath)) {
        throw "缺少章节文件：$chapterPath"
    }

    $chapterText = [System.IO.File]::ReadAllText($chapterPath, [System.Text.Encoding]::UTF8).Trim()
    $parts.Add("---`r`n`r`n$chapterText")
}

$parts.Add("---`r`n`r`n$($closingMatter.Trim())")
$merged = ($parts -join "`r`n`r`n") + "`r`n"
[System.IO.File]::WriteAllText($outputPath, $merged, [System.Text.UTF8Encoding]::new($false))

Write-Output "已生成：$outputPath"
