## 写在前面

第二册结束时，李世民把一个仍在运转的帝国交给了儿子。

这听上去比隋末的遍地烽火轻松得多。长安没有被围，仓库还能开门，三省六部知道怎样办事，边将也没有趁皇帝去世立即起兵。李治不必重新建立唐朝，只要坐到父亲的位置上，让一切继续运转。

问题恰恰出在“继续”两个字上。

太宗留下的不只有制度，还有替他运转制度的人；不只有经验，还有经验形成的答案。长孙无忌、褚遂良和李勣能够保护年轻皇帝，也会让年轻皇帝不断看见父亲的影子。李治要获得自主，不能只接过玉玺，还要证明当顾命大臣不同意时，自己的决定仍然能够穿过宫门，成为国家命令。

武氏就是从这道裂缝中走进来的。

她的道路不是从皇后直接通向皇帝。她先从感业寺回到宫籍，从才人的旧身份升到昭仪，再把生育、宠爱和宫中消息变成政治筹码；她与高宗合作打破旧臣的否决，又在高宗疾病加重后进入奏章与人事。等她真正称帝，权力已经不只在帘后，而被写进官名、礼仪、建筑、选官与告密制度。

所以第三册不只是武则天的个人传记。

它要写的是，贞观时代由皇帝与名臣共同维护的秩序，怎样变成高宗与武后共同执政的结构；这种结构又怎样在皇子、边疆、酷吏、考场和继承问题上不断承受压力。武则天确实打破了许多旧门槛，也确实制造了新的恐惧。评价她，既不能只剩“千古女帝”的赞叹，也不能把几十年政治压缩成后宫阴谋。

全册仍沿着“控制与失控”的主线前进。高宗为摆脱顾命者而集中决断，武后为保护自己而建立新网络，帝国为控制远方而设置都护府、驿站与驻军，朝廷为绕过旧门第而扩大选官和信息入口。每一种控制都解决了真实问题，也可能产生新的失控：案卷可以清除政敌，告密可以越过官僚阻塞，考场可以打开上升道路，边疆胜利可以把补给线拉到难以承受的地方。

人物会在事件中作出选择，制度会在执行中暴露代价。对于小公主之死、李弘死因、李贤谋反、《黄台瓜辞》、武则天晚年的宫廷传闻等争议，本册只写材料能够支持的层次。能够确定的行动与结果进入故事，动机留有推断余地，越是戏剧性完整的细节，越不急着替古人宣布真相。

这一册从一位新皇帝在灵柩前接过国家开始，到一位女皇在上阳宫结束生命为止。

五十多年里，坐在御座上的人几次改变，御座背后的问题却始终没有变：权力怎样证明自己有资格决定，又怎样在决定一切以前，给不同意见留下活路。

